<?php

declare(strict_types=1);

namespace Ws\Http\Automated;

use Ws\Http\Contract\CookieStoreInterface;
use Ws\Http\Response;

/**
 * 持久化 cookie jar(design/16 §7,settings.cookieStore=file:<path>)。
 *
 * memory jar 语义 + 场景级持久化:
 * - 构造时文件存在 → 加载(Netscape cookie 文件格式);
 * - persist() → 落盘(Runner::run 结束时调用;文件不存在则创建,目录不存在抛 401);
 * - 格式:Netscape(# Netscape HTTP Cookie File 制式;制表符分隔 7 字段:
 *   domain / flag / path / secure / expiry(unix ts,0=会话) / name / value)。
 *
 * 作用域语义与 memory 一致(按主机精确匹配,不做域名后缀匹配)。
 */
final class FileCookieStore implements CookieStoreInterface
{
    /** @var array<string, array<string, array{value: string, expires: int}>> host => name => {value, expires} */
    private $jar = [];

    /** @var string 落盘路径 */
    private $path;

    public function __construct(string $path)
    {
        $this->path = $path;

        if (is_file($path)) {
            $this->load($path);
        }
    }

    public function path(): string
    {
        return $this->path;
    }

    /**
     * 落盘(Netscape 格式;Runner::run 结束时调用)。
     */
    public function persist(): void
    {
        $this->pruneExpired();

        $lines = ["# Netscape HTTP Cookie File", "# Generated by ws-http Automated; host-only (no suffix matching)"];
        foreach ($this->jar as $host => $cookies) {
            foreach ($cookies as $name => $entry) {
                $lines[] = sprintf(
                    "%s\tTRUE\t/\tFALSE\t%d\t%s\t%s",
                    $host,
                    $entry['expires'], // 0 = 会话 cookie(Netscape 惯例)
                    $name,
                    $entry['value']
                );
            }
        }

        if (@file_put_contents($this->path, implode("\n", $lines) . "\n") === false) {
            throw new AutomatedException(
                sprintf('cookie store: cannot write "%s"', $this->path),
                403 // 4xx 引擎段:文件系统不可写(运行环境错误,非 JSON/字段校验)
            );
        }
    }

    public function cookieHeaderFor(string $url): ?string
    {
        $host = $this->hostOf($url);
        if ($host === null || !isset($this->jar[$host])) {
            return null;
        }

        $now = time();
        $pairs = [];
        foreach ($this->jar[$host] as $name => $entry) {
            if ($entry['expires'] !== 0 && $entry['expires'] < $now) {
                unset($this->jar[$host][$name]); // 过期剔除
                continue;
            }
            $pairs[] = $name . '=' . $entry['value'];
        }

        return $pairs === [] ? null : implode('; ', $pairs);
    }

    public function collectFrom(Response $response, string $url): void
    {
        $host = $this->hostOf($url);
        if ($host === null) {
            return;
        }

        foreach ($response->headers->all('Set-Cookie') as $setCookie) {
            $parsed = $this->parseSetCookie($setCookie);
            if ($parsed === null) {
                continue;
            }
            [$name, $value, $expires] = $parsed;
            $this->jar[$host][$name] = ['value' => $value, 'expires' => $expires];
        }
    }

    /**
     * 从 Netscape 格式文件加载;损坏行跳过(容忍注释/空行/字段缺失)。
     */
    private function load(string $path): void
    {
        $raw = @file_get_contents($path);
        if ($raw === false) {
            return; // 读失败 = 空加载(与 FileConversationStore 损坏容错同哲学)
        }

        foreach (explode("\n", $raw) as $line) {
            $line = rtrim($line, "\r");
            if ($line === '' || $line[0] === '#') {
                continue; // 注释/空行(# HttpOnly_ 前缀扩展行也按注释跳过——本实现不产生)
            }
            $fields = explode("\t", $line);
            if (count($fields) < 7) {
                continue; // 字段不足 = 损坏行,跳过
            }
            [$domain, , , , $expiry, $name, $value] = $fields;
            if ($domain === '' || $name === '') {
                continue;
            }
            $host = strtolower(ltrim($domain, '.'));
            $this->jar[$host][$name] = ['value' => $value, 'expires' => (int) $expiry];
        }
    }

    private function pruneExpired(): void
    {
        $now = time();
        foreach ($this->jar as $host => $cookies) {
            foreach ($cookies as $name => $entry) {
                if ($entry['expires'] !== 0 && $entry['expires'] < $now) {
                    unset($this->jar[$host][$name]);
                }
            }
            if ($this->jar[$host] === []) {
                unset($this->jar[$host]);
            }
        }
    }

    /**
     * 解析单条 Set-Cookie:name=value; Expires=...; Path=...
     *
     * @return array{0: string, 1: string, 2: int}|null [name, value, expires(unix ts;0=会话)]
     */
    private function parseSetCookie(string $header): ?array
    {
        $parts = explode(';', $header);
        // explode 至少返回一个元素,array_shift 恒取到 string
        $first = (string) array_shift($parts);

        if ($first === '') {
            return null;
        }

        $eq = strpos($first, '=');
        if ($eq === false || $eq === 0) {
            return null;
        }

        $name = trim(substr($first, 0, $eq));
        $value = trim(substr($first, $eq + 1));
        $expires = 0;

        foreach ($parts as $attribute) {
            $attrParts = explode('=', trim($attribute), 2);
            if (strcasecmp($attrParts[0], 'Expires') === 0 && isset($attrParts[1])) {
                $ts = strtotime($attrParts[1]);
                $expires = $ts === false ? 0 : $ts;
            }
        }

        return [$name, $value, $expires];
    }

    private function hostOf(string $url): ?string
    {
        $host = parse_url($url, PHP_URL_HOST);

        return \is_string($host) && $host !== '' ? strtolower($host) : null;
    }
}
